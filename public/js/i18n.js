  function createI18n(initial) {
    let lang = DICT[initial] ? initial : 'vi';
    const listeners = [];
    return {
      get lang() { return lang; },
      set(next) {
        if (!DICT[next]) return;
        lang = next;
        document.documentElement.lang = next;
        listeners.forEach((fn) => fn(next));
      },
      onChange(fn) { listeners.push(fn); },
      t(key, vars) {
        let s = (DICT[lang] && DICT[lang][key]) ?? (DICT.vi[key]) ?? key;
        if (vars) {
          Object.keys(vars).forEach((k) => { s = s.split(`{${k}}`).join(String(vars[k])); });
        }
        return s;
      },
      status(code) { return (STATUS_LABELS[lang] || STATUS_LABELS.vi)[code] || code; },
    };
  }

  global.KineraI18n = { createI18n, DICT, STATUS_LABELS };
